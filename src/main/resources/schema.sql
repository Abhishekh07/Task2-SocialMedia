CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 bio VARCHAR(180) DEFAULT 'Hey there! I am new here.'
);
CREATE TABLE IF NOT EXISTS posts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL, content VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 content VARCHAR(500) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS likes (user_id BIGINT NOT NULL, post_id BIGINT NOT NULL, PRIMARY KEY(user_id,post_id));
CREATE TABLE IF NOT EXISTS follows (follower_id BIGINT NOT NULL, following_id BIGINT NOT NULL, PRIMARY KEY(follower_id,following_id));
